/**
 * Find country info by country name or 2-letter ISO code.
 */
export const getCountry = (query) => {
  if (!query) return null
  const q = String(query).trim().toLowerCase()
  return (
    COUNTRIES.find(
      (c) => c.name.toLowerCase() === q || c.code.toLowerCase() === q
    ) || null
  )
}

/**
 * Return country dialing code (e.g. "+65", "+91") or default fallback.
 */
export const getCountryDialCode = (query, fallback = '+65') => {
  const country = getCountry(query)
  return country?.dialCode || fallback
}

/**
 * Given an existing mobile number and a new country, updates/adds the country dial code.
 */
export const applyCountryDialCode = (currentPhone, newCountry) => {
  const dialCode = getCountryDialCode(newCountry, '')
  if (!dialCode) return currentPhone || ''

  const trimmed = (currentPhone || '').trim()
  if (!trimmed) {
    return `${dialCode} `
  }

  // If already starts with a plus and country code like +65 or +91, replace it
  const match = trimmed.match(/^\+\d{1,4}\s*(.*)$/)
  if (match) {
    const rest = match[1]
    return `${dialCode} ${rest}`.trimEnd() + (rest ? '' : ' ')
  }

  // If purely digits or standard local number, prefix it
  return `${dialCode} ${trimmed}`
}
